/**
 * Contact enrichment domain types.
 *
 * verification_status semantics (never a deliverability guarantee):
 *  - publicly_confirmed : the address was published by the company/person themselves (their site, GitHub profile…)
 *                         and the page evidence ties it to the founder / company. MX valid.
 *  - provider_verified  : a verification provider reported the mailbox as valid AND we have name attribution.
 *  - domain_valid_only  : a real address seen on a page, but attribution is weak (e.g. third-party page);
 *                         the domain accepts mail (MX) — that does NOT prove the mailbox exists.
 *  - pattern_guessed    : generated by us from a naming pattern (first@domain). Never used for outreach.
 *  - unverified         : found only in model text, or the domain has no mail server.
 */
export type VerificationStatus = "publicly_confirmed" | "provider_verified" | "domain_valid_only" | "pattern_guessed" | "unverified";
export type DiscoverySource = "company_website" | "github" | "web_search" | "pattern" | "manual";
export type ContactKind = "founder" | "company" | "contact_form";
export type MailboxRole = "general" | "partnerships" | "press" | "support" | "other";
export type ContactStatus = "pending" | "in_progress" | "completed" | "not_found" | "failed";

export const STATUS_RANK: Record<VerificationStatus, number> = {
  publicly_confirmed: 4,
  provider_verified: 3,
  domain_valid_only: 2,
  pattern_guessed: 1,
  unverified: 0,
};

/** Statuses that are safe to prefill into an outreach draft. */
export const OUTREACH_SAFE: ReadonlySet<VerificationStatus> = new Set(["publicly_confirmed", "provider_verified"]);

export interface FounderRef {
  id: string | null;
  name: string;
  role: string | null;
}

export interface StartupRef {
  id: string;
  name: string;
  website: string | null;
  domain: string | null;
  contactStatus: ContactStatus;
  contactCheckedAt: string | null;
}

export interface ContactCandidate {
  kind: ContactKind;
  email: string | null;
  contactUrl: string | null;
  founderId: string | null;
  founderName: string | null;
  mailboxRole: MailboxRole | null;
  status: VerificationStatus;
  source: DiscoverySource;
  sourceUrl: string | null;
  evidence: string | null;
  mxValid: boolean | null;
  /** Heuristic ranking aid (0-100). Not a probability of deliverability. */
  confidence: number;
}

export interface StoredContact extends ContactCandidate {
  id: string | null;
  isPreferred: boolean;
  firstFoundAt: string | null;
}

export const contactKey = (c: Pick<ContactCandidate, "email" | "contactUrl">): string => (c.email ? `e:${c.email.toLowerCase()}` : `u:${c.contactUrl}`);
